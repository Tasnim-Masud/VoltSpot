  getLang(params) {
    return params.get('lang') === 'bn' ? 'bn' : 'en';
  },

  t(lang, key) {
    const dict = this.translations[lang] || this.translations.en;
    return dict[key] != null ? dict[key] : (this.translations.en[key] || key);
  },

  // Translates every element with a data-i18n="key" attribute (textContent)
  // and data-i18n-placeholder="key" attribute (placeholder text). Elements
  // with data-i18n-html="key" get innerHTML instead — used only where a
  // translation needs embedded markup (e.g. a highlighted word), since
  // word order differs enough between English and Bangla that a fixed
  // "before/highlight/after" span split doesn't work for both.
  apply(lang) {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      el.textContent = this.t(lang, key);
    });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      const key = el.getAttribute('data-i18n-html');
      el.innerHTML = this.t(lang, key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.setAttribute('placeholder', this.t(lang, key));
    });
    document.documentElement.setAttribute('lang', lang === 'bn' ? 'bn' : 'en');
  },
